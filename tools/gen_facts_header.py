"""Facts header generator (standard library and hawk; reads the facts of each raptor wing through hawk/facts.py).

For each raptor wing whose resolved facts hold ``linalg.max_dim`` it writes ``staging/raptor/wings/<name>/raptor_facts.h``: the facts that
C++ reads, as named macros. A translation unit that includes aether's linalg or ray headers includes this header first; its directory is
on the compile line (``-I``), so the file is a named input of the compile. Usage: gen_facts_header.py [--check]  (--check: exit 1 on drift)."""
import pathlib
import sys

TREE = pathlib.Path(__file__).resolve().parent.parent
WINGS = TREE / "staging" / "raptor" / "wings"
HEADER = "raptor_facts.h"


def _facts():
    sys.path.insert(0, str(TREE))
    from hawk import facts

    return facts


def generate(name: str, data: dict) -> str:
    up = name.upper()
    team = data["linalg"].get("team_max_dim")
    team_lines = [] if team is None else [
        "/* up to this dimension a team of threads works on a matrix (aether::linalg team_max_dim) */",
        f"#define RAPTOR_LINALG_TEAM_MAX_DIM {int(team)}"]
    return "\n".join([
        f"/* GENERATED by tools/gen_facts_header.py from the raptor wing {name}. Do not edit. */",
        f"#ifndef RAPTOR_FACTS_{up}_H",
        f"#define RAPTOR_FACTS_{up}_H",
        "",
        f'#define RAPTOR_WING_NAME "{name}"',
        "/* up to this dimension one thread holds a matrix (aether::linalg::max_dim) */",
        f"#define RAPTOR_LINALG_MAX_DIM {int(data['linalg']['max_dim'])}",
        *team_lines,
        "",
        f"#endif /* RAPTOR_FACTS_{up}_H */",
        ""])


def headers() -> dict:
    """``{wing folder: text}`` of every raptor wing whose resolved facts hold ``linalg.max_dim``."""
    facts = _facts()
    out = {}
    for manifest in sorted(WINGS.glob("*/wing.json")):
        data = facts.load(manifest.parent.name)
        if "max_dim" in data.get("linalg", {}):
            out[manifest.parent] = generate(manifest.parent.name, data)
    return out


def drift() -> list:
    """The names of the wings whose header is absent or is not what their resolved facts generate."""
    return [d.name for d, text in headers().items() if not (d / HEADER).is_file() or (d / HEADER).read_text() != text]


def main(argv):
    if "--check" in argv:
        return 1 if drift() else 0
    for d, text in headers().items():
        (d / HEADER).write_text(text, newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
