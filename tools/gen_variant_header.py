"""Variant header generator (standard library only; reads variants/ through hawk/variants.py, loaded by path).

For each variant that holds ``linalg.max_dim`` it writes ``variants/<name>/raptor_variant.h``: the variant's facts that C++ reads, as
named macros. A translation unit that includes aether's linalg or ray headers includes this header first; its directory is on the
compile line (``-I``), so the file is a named input of the compile. Usage: gen_variant_header.py [--check]  (--check: exit 1 on drift)."""
import importlib.util
import pathlib
import sys

TREE = pathlib.Path(__file__).resolve().parent.parent
HEADER = "raptor_variant.h"


def _loader():
    spec = importlib.util.spec_from_file_location("_variants", TREE / "hawk" / "variants.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules["_variants"] = module
    spec.loader.exec_module(module)
    return module


def generate(name: str, data: dict) -> str:
    up = name.upper()
    team = data["linalg"].get("team_max_dim")
    team_lines = [] if team is None else [
        "/* up to this dimension a team of threads works on a matrix (aether::linalg team_max_dim) */",
        f"#define RAPTOR_LINALG_TEAM_MAX_DIM {int(team)}"]
    return "\n".join([
        f"/* GENERATED by tools/gen_variant_header.py from variants/{name}/. Do not edit. */",
        f"#ifndef RAPTOR_VARIANT_{up}_H",
        f"#define RAPTOR_VARIANT_{up}_H",
        "",
        f'#define RAPTOR_VARIANT_NAME "{name}"',
        "/* up to this dimension one thread holds a matrix (aether::linalg::max_dim) */",
        f"#define RAPTOR_LINALG_MAX_DIM {int(data['linalg']['max_dim'])}",
        *team_lines,
        "",
        f"#endif /* RAPTOR_VARIANT_{up}_H */",
        ""])


def main(argv):
    variants = _loader()
    drift = 0
    for path in sorted((TREE / "variants").glob("*/data.py")):
        name = path.parent.name
        data = variants.load(name)
        if "linalg" not in data:
            continue
        out, text = path.parent / HEADER, generate(name, data)
        if "--check" in argv:
            drift += not out.is_file() or out.read_text() != text
        else:
            out.write_text(text, newline="\n")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
